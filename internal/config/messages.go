var compiledMessages = func() []*regexp.Regexp {
	out := make([]*regexp.Regexp, len(messages))
	for i, m := range messages {
		out[i] = regexp.MustCompile(m[0])
	}
	return out
}()

func Translate(lang, message string) string {
	if !IsChinese(lang) {
		return message
	}
	out := strings.Split(message, "\n")
	for n, line := range out {
		for i, pattern := range compiledMessages {
			if pattern.MatchString(line) {
				out[n] = pattern.ReplaceAllString(line, messages[i][1])
				break
			}
		}
	}
	return strings.Join(out, "\n")
}
